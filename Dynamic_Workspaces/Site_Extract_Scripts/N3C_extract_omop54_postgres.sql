/**
OMOP v5.4 extraction code for N3C - Phenotype Agnostic (all data) - Postgres
Ported from tenant-pilot/ExtractScripts/N3C_extract_omop_mssql.sql (OMOP 5.3.1, N3C Clinical Pilot)

HOW TO RUN:
If you are not using the R or Python exporters, you will need to find and replace @cdmDatabaseSchema and @resultsDatabaseSchema with your local OMOP 5.4 schema details

USER NOTES:
This extract pulls the following OMOP 5.4 tables: PERSON, OBSERVATION_PERIOD, VISIT_OCCURRENCE, CONDITION_OCCURRENCE, DRUG_EXPOSURE, DEVICE_EXPOSURE, PROCEDURE_OCCURRENCE, MEASUREMENT, OBSERVATION, DEATH, LOCATION, CARE_SITE, PROVIDER, DRUG_ERA, CONDITION_ERA
As an OMOP site, you are expected to be populating derived tables (OBSERVATION_PERIOD, DRUG_ERA, CONDITION_ERA)
Please refer to the OMOP site instructions for assistance on how to generate these tables.
EPISODE and EPISODE_EVENT (new in OMOP 5.4) are not extracted.

SCRIPT ASSUMPTIONS:
1. You have already built the N3C_CLINICAL_COHORT table (with that name) by running N3C_clinical_cohort_omop54_postgres.sql prior to running this extract
2. You are extracting data with a lookback period to 1-1-2018
3. You have existing tables for each of these extracted tables. If you do not, at a minimum, you MUST create a shell table so it can extract an empty table. Failure to create shells for missing table will result in ingestion problems.
4. Your CDM is OMOP 5.4. This script will fail on a 5.3 database because VISIT_OCCURRENCE column names changed in 5.4.
